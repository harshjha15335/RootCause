"""Exports JSON Schema for contracts 1 and 2 into docs/engine/ and docs/ENGINE.md.

    python scripts/export_schema.py

Role 1 can generate TypeScript types from docs/engine/*.json
(e.g. npx json-schema-to-typescript docs/engine/match_event.schema.json).
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from engine.models import EvidencePackage, MatchEvent, MatchMeta

MODELS = {"match_event": MatchEvent, "match_meta": MatchMeta, "evidence_package": EvidencePackage}
START, END = "<!-- schema:start -->", "<!-- schema:end -->"


def main() -> None:
    schema_dir = ROOT / "docs" / "engine"
    schema_dir.mkdir(parents=True, exist_ok=True)
    blocks = []
    for name, model in MODELS.items():
        schema = json.dumps(model.model_json_schema(), indent=2)
        (schema_dir / f"{name}.schema.json").write_text(schema + "\n", encoding="utf-8")
        blocks.append(
            f"### `{model.__name__}`\n\n<details><summary>JSON Schema</summary>\n\n```json\n{schema}\n```\n\n</details>\n"
        )
    spec = ROOT / "docs" / "ENGINE.md"
    text = spec.read_text(encoding="utf-8")
    generated = (
        f"{START}\n<!-- generated by scripts/export_schema.py, do not edit by hand -->\n\n"
        + "\n".join(blocks)
        + END
    )
    spec.write_text(
        re.sub(
            re.escape(START) + ".*?" + re.escape(END), lambda _: generated, text, flags=re.DOTALL
        ),
        encoding="utf-8",
    )
    print(f"wrote {len(MODELS)} schemas")


if __name__ == "__main__":
    main()
